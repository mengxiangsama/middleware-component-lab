package io.github.quartzlab;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.quartz.JobBuilder;
import org.quartz.JobKey;
import org.quartz.Scheduler;
import org.quartz.SimpleScheduleBuilder;
import org.quartz.SimpleTrigger;
import org.quartz.Trigger;
import org.quartz.TriggerBuilder;
import org.quartz.TriggerKey;
import org.quartz.impl.matchers.KeyMatcher;
import org.quartz.listeners.TriggerListenerSupport;
import org.springframework.boot.Banner;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.context.ConfigurableApplicationContext;
import org.springframework.jdbc.core.JdbcTemplate;

import java.nio.file.Path;
import java.time.Duration;
import java.time.Instant;
import java.time.LocalDate;
import java.util.Date;
import java.util.concurrent.atomic.AtomicReference;

import static org.assertj.core.api.Assertions.assertThat;
import static org.awaitility.Awaitility.await;

class QuartzRestartTest {
    private static final JobKey JOB = JobKey.jobKey("store-a-close", "reconciliation");
    private static final TriggerKey TRIGGER = TriggerKey.triggerKey("store-a-scheduled", "reconciliation");
    private static final String STORE_ID = "store-a";
    private static final LocalDate BUSINESS_DATE = LocalDate.of(2026, 11, 22);

    @TempDir
    Path workspace;

    @Test
    void firesPersistedMissedTriggerAfterRestart() throws Exception {
        Date originalFireTime = Date.from(Instant.now().minusSeconds(90));
        Scheduler original;
        try (var first = start("always")) {
            first.getBean(JdbcTemplate.class).execute("""
                    CREATE TABLE reconciliation_runs (
                        run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        store_id VARCHAR(40) NOT NULL,
                        business_date DATE NOT NULL
                    )
                    """);
            original = first.getBean(Scheduler.class);
            var job = JobBuilder.newJob(ReconcileStoreJob.class)
                    .withIdentity(JOB)
                    .usingJobData("storeId", STORE_ID)
                    .usingJobData("businessDate", BUSINESS_DATE.toString())
                    .storeDurably()
                    .build();
            var trigger = TriggerBuilder.newTrigger()
                    .withIdentity(TRIGGER)
                    .forJob(JOB)
                    .startAt(originalFireTime)
                    .withSchedule(SimpleScheduleBuilder.simpleSchedule().withMisfireHandlingInstructionFireNow())
                    .build();
            assertThat(original.getMetaData().isJobStoreSupportsPersistence()).isTrue();
            assertThat(original.scheduleJob(job, trigger)).isEqualTo(originalFireTime);
        }
        assertThat(original.isShutdown()).isTrue();
        assertThat(workspace.resolve("quartz.mv.db")).isRegularFile();

        try (var restarted = start("never")) {
            var scheduler = restarted.getBean(Scheduler.class);
            var jdbc = restarted.getBean(JdbcTemplate.class);
            var recovered = scheduler.getTrigger(TRIGGER);
            assertThat(recovered).isNotNull();
            assertThat(recovered.getNextFireTime()).isEqualTo(originalFireTime);
            assertThat(recovered.getJobKey()).isEqualTo(JOB);
            assertThat(recovered.getMisfireInstruction()).isEqualTo(SimpleTrigger.MISFIRE_INSTRUCTION_FIRE_NOW);
            assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM reconciliation_runs", Integer.class)).isZero();

            var misfired = new AtomicReference<TriggerKey>();
            scheduler.getListenerManager().addTriggerListener(new TriggerListenerSupport() {
                @Override
                public String getName() {
                    return "lab-misfire";
                }

                @Override
                public void triggerMisfired(Trigger trigger) {
                    misfired.set(trigger.getKey());
                }
            }, KeyMatcher.keyEquals(TRIGGER));

            scheduler.start();
            await().atMost(Duration.ofSeconds(10)).untilAsserted(() -> {
                assertThat(misfired.get()).isEqualTo(TRIGGER);
                assertThat(scheduler.getTrigger(TRIGGER)).isNull();
                assertThat(jdbc.query("SELECT store_id, business_date FROM reconciliation_runs",
                        (row, index) -> new Run(row.getString(1), row.getObject(2, LocalDate.class))))
                        .containsExactly(new Run(STORE_ID, BUSINESS_DATE));
            });
        }
    }

    private ConfigurableApplicationContext start(String schemaInitialization) {
        return new SpringApplicationBuilder(QuartzJdbcLabApplication.class)
                .web(WebApplicationType.NONE)
                .bannerMode(Banner.Mode.OFF)
                .run("--spring.datasource.url=jdbc:h2:file:" + workspace.resolve("quartz"),
                        "--spring.datasource.username=sa",
                        "--spring.datasource.password=",
                        "--spring.quartz.auto-startup=false",
                        "--spring.quartz.jdbc.initialize-schema=" + schemaInitialization,
                        "--spring.quartz.properties.org.quartz.jobStore.misfireThreshold=1000");
    }

    private record Run(String storeId, LocalDate businessDate) {
    }
}
